// TUI popup uses the core-side types directly so there's a single registry
// describing every setting, its kind, and its display metadata.
pub type SettingKind = TuiSettingKind;
pub type SettingEntry = TuiSettingDecl;

/// Cycle to the next/previous option in a fixed list, given the current value.
/// Returns the first option if `current` isn't in the list.
fn cycle_option<'a>(options: &'a [&'a str], current: &str, forward: bool) -> &'a str {
    let idx = options.iter().position(|&o| o == current).unwrap_or(0);
    let len = options.len();
    let next = if forward {
        (idx + 1) % len
    } else {
        (idx + len - 1) % len
    };
    options[next]
}

#[derive(Clone, Debug, PartialEq)]
pub enum EditMode {
    Browsing,
    Editing {
        buffer: String,
    },
    ConfirmReset,
    SelectingModel {
        selected: usize,
        scroll_offset: usize,
    },
}

pub struct SettingsPopup {
    visible: bool,
    /// Visible TUI rows for the current popup session. Rebuilt on each
    /// `show()` so channel-specific rows (Signal/Discord/Slack) only appear
    /// when their credentials are configured. Sourced from `TUI_SETTINGS`.
    entries: Vec<&'static SettingEntry>,
    selected: usize,
    mode: EditMode,
    status_message: Option<(String, bool)>, // (message, is_success)
    /// Daemon client for setting reads/writes. `None` only in tests that
    /// poke at the popup via direct field access.
    client: Option<Arc<Mutex<DaemonClient>>>,
    /// Snapshot of the keys the daemon has stored as overrides — used by
    /// `setting_source` to render the "customized" dot. Refreshed on `show()`
    /// and after every successful write.
    customized_keys: HashSet<String>,
    provider_index: usize,
    model_index: usize,
}

// Settings live in `cortex::settings::TUI_SETTINGS`, generated by the
// `define_settings!` macro in `crates/core/src/config/settings_table.rs`.
// The popup renders entries in their declared order; category changes
// produce section headers.

/// Filter `TUI_SETTINGS` down to the rows that should be visible for this
/// `Config`. Channel-specific rows (Signal/Discord/Slack) only render when
/// their credentials are configured — a Telegram-only user shouldn't see
/// Signal-CLI settings cluttering the popup.
///
/// Predicates use credential presence (the same signal `channel_init.rs`
/// uses to decide whether to spin up a client) rather than a hypothetical
/// `gateway.<channel>_enabled` flag, which doesn't exist in the schema.
fn visible_entries(config: &Config) -> Vec<&'static SettingEntry> {
    let signal_on = config.resolve_credential_or_env("SIGNAL_ACCOUNT").is_some();
    let discord_on = config
        .resolve_credential_or_env("DISCORD_BOT_TOKEN")
        .is_some();
    let slack_on = config
        .resolve_credential_or_env("SLACK_BOT_TOKEN")
        .is_some();
    let provider = config
        .llm
        .provider
        .as_deref()
        .and_then(|id| cortex::llm::provider::Provider::from_str(id).ok());
    let provider_uses_api_key = provider
        .map(|provider| provider.requires_api_key())
        .unwrap_or(true);
    let provider_is_bedrock = matches!(provider, Some(cortex::llm::provider::Provider::Bedrock));
    let provider_is_azure_openai =
        matches!(provider, Some(cortex::llm::provider::Provider::AzureOpenAi));
    TUI_SETTINGS
        .iter()
        .filter(|e| match e.key {
            "llm.api_key" | "llm.api_key_env" => provider_uses_api_key,
            "llm.bedrock_region" | "llm.bedrock_endpoint_url" | "llm.bedrock_use_fips" => {
                provider_is_bedrock
            }
            "llm.azure_resource" | "llm.azure_deployment" | "llm.azure_api_version" => {
                provider_is_azure_openai
            }
            "gateway.signal_cli_host" | "gateway.signal_cli_port" => signal_on,
            "gateway.discord_guild_allowlist" => discord_on,
            "gateway.slack_channel_allowlist" => slack_on,
            _ => true,
        })
        .collect()
}

impl SettingsPopup {
    pub fn new() -> Self {
        Self {
            visible: false,
            entries: TUI_SETTINGS.iter().collect(),
            selected: 0,
            mode: EditMode::Browsing,
            status_message: None,
            client: None,
            customized_keys: HashSet::new(),
            provider_index: 0,
            model_index: 0,
        }
    }

    pub fn is_visible(&self) -> bool {
        self.visible
    }

    pub fn show(&mut self, config: &Config, client: &Arc<Mutex<DaemonClient>>) {
        self.visible = true;
        self.entries = visible_entries(config);
        self.selected = 0;
        self.mode = EditMode::Browsing;
        self.status_message = None;
        self.client = Some(client.clone());
        self.refresh_customized_keys();
        self.sync_select_indices(config);
    }

    /// Pull the current set of override-keys from the daemon so the
    /// `customized` indicator stays accurate. Best-effort: an RPC failure
    /// just leaves the cached set as-is and logs.
    fn refresh_customized_keys(&mut self) {
        let Some(client) = self.client.clone() else {
            return;
        };
        let Some(handle) = tokio::runtime::Handle::try_current().ok() else {
            return;
        };
        let snap = tokio::task::block_in_place(|| {
            handle.block_on(async move {
                let mut c = client.lock().await;
                c.get_settings().await
            })
        });
        match snap {
            Ok(snap) => {
                self.customized_keys = snap.entries.into_iter().map(|e| e.key).collect();
            }
            Err(e) => {
                tracing::warn!("settings_popup: get_settings failed: {e}");
            }
        }
    }

    /// Run an admin RPC from the sync popup-handler context.
    fn block_on_rpc<F, T>(&self, f: F) -> Option<anyhow::Result<T>>
    where
        F: for<'b> FnOnce(
            &'b mut DaemonClient,
        ) -> std::pin::Pin<
            Box<dyn std::future::Future<Output = anyhow::Result<T>> + Send + 'b>,
        >,
    {
        let client = self.client.clone()?;
        let handle = tokio::runtime::Handle::try_current().ok()?;
        Some(tokio::task::block_in_place(|| {
            handle.block_on(async move {
                let mut c = client.lock().await;
                f(&mut c).await
            })
        }))
    }

    /// Sync provider_index and model_index from the current config values.
    fn sync_select_indices(&mut self, config: &Config) {
        let provider_id = config.llm.provider.as_deref().unwrap_or("openrouter");
        self.provider_index = PROVIDERS
            .iter()
            .position(|(id, _, _)| *id == provider_id)
            .unwrap_or(0);

        let models = models_for_provider(provider_id);
        self.model_index = models
            .iter()
            .position(|(id, _)| *id == config.llm.model.as_str())
            .unwrap_or(0);
    }

    pub fn dismiss(&mut self) {
        self.visible = false;
        self.mode = EditMode::Browsing;
        self.status_message = None;
    }

    /// Force the popup into `Editing` mode. Test-only backdoor for verifying
    /// that downstream logic (e.g. the global `/` interceptor in the App)
    /// correctly defers to `wants_text_input()`.
    #[cfg(test)]
    pub(super) fn force_editing_for_test(&mut self, buffer: String) {
        self.mode = EditMode::Editing { buffer };
    }

    fn current_value(&self, config: &Config, key: &str) -> String {
        // Secret entries must never echo the raw value to the UI.
        if self.entry_for_key(key).map(|e| e.kind) == Some(SettingKind::Secret) {
            let raw = cortex::settings::config_value_for_key(config, key).unwrap_or_default();
            return if raw.trim().is_empty() {
                "(not set)".to_string()
            } else {
                "(set)".to_string()
            };
        }

        match key {
            "provider" => {
                let (_, display, _) = PROVIDERS.get(self.provider_index).unwrap_or(&PROVIDERS[0]);
                display.to_string()
            }
            "model" => {
                let provider_id = PROVIDERS
                    .get(self.provider_index)
                    .map(|(id, _, _)| *id)
                    .unwrap_or("openrouter");
                let models = models_for_provider(provider_id);
                models
                    .get(self.model_index)
                    .map(|(_, display)| display.to_string())
                    .unwrap_or_else(|| config.llm.model.clone())
            }
            _ => cortex::settings::config_value_for_key(config, key)
                .unwrap_or_else(|| "?".to_string()),
        }
    }

    fn entry_for_key(&self, key: &str) -> Option<&'static SettingEntry> {
        self.entries.iter().find(|e| e.key == key).copied()
    }

    /// Handle a bracketed paste event. Returns `true` if the paste was consumed
    /// (i.e. the popup is visible and in text-editing mode).
    pub fn handle_paste(&mut self, text: &str) -> bool {
        if !self.visible {
            return false;
        }
        if let EditMode::Editing { ref mut buffer } = self.mode {
            buffer.push_str(text);
            return true;
        }
        false
    }

    pub fn handle_key(
        &mut self,
        key: crossterm::event::KeyEvent,
        config: &mut Config,
    ) -> anyhow::Result<Option<AppAction>> {
        // Dispatch to a per-mode handler. Each handler owns its own key map;
        // cross-mode transitions are done by assigning to `self.mode`.
        match self.mode {
            EditMode::Browsing => self.handle_key_browsing(key, config),
            EditMode::ConfirmReset => self.handle_key_confirm_reset(key, config),
            EditMode::Editing { .. } => self.handle_key_editing(key, config),
            EditMode::SelectingModel { .. } => self.handle_key_selecting_model(key, config),
        }
    }

    fn handle_key_browsing(
        &mut self,
        key: crossterm::event::KeyEvent,
        config: &mut Config,
    ) -> anyhow::Result<Option<AppAction>> {
        use crossterm::event::KeyCode;

        match key.code {
            KeyCode::Esc => {
                self.dismiss();
                Ok(None)
            }
            KeyCode::Up => {
                if self.selected == 0 {
                    self.selected = self.entries.len() - 1;
                } else {
                    self.selected -= 1;
                }
                self.status_message = None;
                Ok(None)
            }
            KeyCode::Down => {
                self.selected = (self.selected + 1) % self.entries.len();
                self.status_message = None;
                Ok(None)
            }
            KeyCode::Char(' ') => {
                let entry = &self.entries[self.selected];
                if entry.kind == SettingKind::Bool {
                    return self.toggle_bool(config);
                }
                Ok(None)
            }
            KeyCode::Left => {
                let entry = &self.entries[self.selected];
                if entry.key == "model" {
                    return self.open_model_selection();
                }
                match entry.kind {
                    SettingKind::Select => self.cycle_select(config, false),
                    SettingKind::Float => self.step_float(config, false),
                    _ => Ok(None),
                }
            }
            KeyCode::Right => {
                let entry = &self.entries[self.selected];
                if entry.key == "model" {
                    return self.open_model_selection();
                }
                match entry.kind {
                    SettingKind::Select => self.cycle_select(config, true),
                    SettingKind::Float => self.step_float(config, true),
                    _ => Ok(None),
                }
            }
            KeyCode::Enter => {
                let entry = &self.entries[self.selected];
                if entry.key == "model" {
                    return self.open_model_selection();
                }
                match entry.kind {
                    SettingKind::Bool | SettingKind::Select => {
                        self.dismiss();
                        Ok(None)
                    }
                    SettingKind::Secret => {
                        // Don't seed the buffer with the current masked value —
                        // start empty so users type a fresh key.
                        self.mode = EditMode::Editing {
                            buffer: String::new(),
                        };
                        self.status_message = None;
                        Ok(None)
                    }
                    _ => {
                        let current = self.current_value(config, entry.key);
                        // Don't prepopulate with the masked label; use raw value for Text.
                        let buffer = if entry.kind == SettingKind::Text {
                            cortex::settings::config_value_for_key(config, entry.key)
                                .unwrap_or_default()
                        } else {
                            current
                        };
                        self.mode = EditMode::Editing { buffer };
                        self.status_message = None;
                        Ok(None)
                    }
                }
            }
            KeyCode::Char('r') | KeyCode::Char('R') => {
                self.mode = EditMode::ConfirmReset;
                self.status_message = None;
                Ok(None)
            }
            _ => Ok(None),
        }
    }

    fn handle_key_confirm_reset(
        &mut self,
        key: crossterm::event::KeyEvent,
        config: &mut Config,
    ) -> anyhow::Result<Option<AppAction>> {
        use crossterm::event::KeyCode;

        match key.code {
            KeyCode::Char('y') | KeyCode::Char('Y') => {
                let result = self.reset_all_to_defaults(config);
                self.mode = EditMode::Browsing;
                result
            }
            _ => {
                self.mode = EditMode::Browsing;
                self.status_message = None;
                Ok(None)
            }
        }
    }

    fn handle_key_editing(
        &mut self,
        key: crossterm::event::KeyEvent,
        config: &mut Config,
    ) -> anyhow::Result<Option<AppAction>> {
        use crossterm::event::KeyCode;

        let EditMode::Editing { ref mut buffer } = self.mode else {
            return Ok(None);
        };

        match key.code {
            KeyCode::Esc => {
                self.mode = EditMode::Browsing;
                self.status_message = None;
                Ok(None)
            }
            KeyCode::Enter => {
                let value = buffer.clone();
                let entry = &self.entries[self.selected];
                let key_str = entry.key;
                let kind = entry.kind;
                let action = if kind == SettingKind::Secret {
                    self.save_secret(config, key_str, &value)
                } else {
                    self.apply_and_save(config, key_str, &value)
                };
                self.mode = EditMode::Browsing;
                Ok(action)
            }
            KeyCode::Backspace => {
                buffer.pop();
                Ok(None)
            }
            KeyCode::Char(c) => {
                buffer.push(c);
                Ok(None)
            }
            _ => Ok(None),
        }
    }

    fn handle_key_selecting_model(
        &mut self,
        key: crossterm::event::KeyEvent,
        config: &mut Config,
    ) -> anyhow::Result<Option<AppAction>> {
        use crossterm::event::KeyCode;

        let EditMode::SelectingModel {
            ref mut selected,
            ref mut scroll_offset,
        } = self.mode
        else {
            return Ok(None);
        };

        let provider_id = PROVIDERS
            .get(self.provider_index)
            .map(|(id, _, _)| *id)
            .unwrap_or("openrouter");

        match key.code {
            KeyCode::Up => {
                let count = models_for_provider(provider_id).len();
                *selected = if *selected == 0 {
                    count - 1
                } else {
                    *selected - 1
                };
                if *selected < *scroll_offset {
                    *scroll_offset = *selected;
                }
                Ok(None)
            }
            KeyCode::Down => {
                let count = models_for_provider(provider_id).len();
                *selected = (*selected + 1) % count;
                Ok(None)
            }
            KeyCode::Enter => {
                let sel = *selected;
                let models = models_for_provider(provider_id);
                let Some(model_id) = models.get(sel).map(|(id, _)| id.clone()) else {
                    return Ok(None);
                };
                let action = self.apply_and_save(config, "model", &model_id);
                if action.is_some() {
                    self.model_index = sel;
                }
                self.mode = EditMode::Browsing;
                Ok(action)
            }
            KeyCode::Esc => {
                self.mode = EditMode::Browsing;
                self.status_message = None;
                Ok(None)
            }
            _ => Ok(None),
        }
    }

    /// Open the model selection list, pre-selecting the current model.
    fn open_model_selection(&mut self) -> anyhow::Result<Option<AppAction>> {
        self.mode = EditMode::SelectingModel {
            selected: self.model_index,
            scroll_offset: 0,
        };
        self.status_message = None;
        Ok(None)
    }

    fn cycle_select(
        &mut self,
        config: &mut Config,
        forward: bool,
    ) -> anyhow::Result<Option<AppAction>> {
        let key = self.entries[self.selected].key;

        // `provider` is dynamic (PROVIDERS catalog) and also cascades into a
        // model reset; it does not live in TUI_SELECT_CHOICES.
        if key == "provider" {
            return self.cycle_provider(config, forward);
        }

        let Some(options) = tui_select_choices(key) else {
            return Ok(None);
        };
        let current = self.current_value(config, key);
        let new_val = cycle_option(options, &current, forward);
        Ok(self.apply_and_save(config, key, new_val))
    }

    /// Cycle the `provider` setting and reset `model` to the first model for
    /// the new provider. Split from `cycle_select` because of the model
    /// cascade — the rest of Select-kind settings are uniform.
    fn cycle_provider(
        &mut self,
        config: &mut Config,
        forward: bool,
    ) -> anyhow::Result<Option<AppAction>> {
        let count = PROVIDERS.len();
        self.provider_index = if forward {
            (self.provider_index + 1) % count
        } else {
            (self.provider_index + count - 1) % count
        };
        let (id, _, _) = PROVIDERS[self.provider_index];
        let Some(action) = self.apply_and_save(config, "provider", id) else {
            return Ok(None);
        };

        // Best-effort: reset model to the first option for the new provider.
        // We keep the "Updated: provider=..." status and only log on save failure.
        self.model_index = 0;
        let models = models_for_provider(id);
        if let Some((model_id, _)) = models.first() {
            if config.apply_setting("model", model_id).is_ok() {
                if let Err(e) = self.save_setting("model", model_id) {
                    tracing::warn!("Failed to persist model reset: {e}");
                }
            }
        }
        Ok(Some(action))
    }

    fn step_float(
        &mut self,
        config: &mut Config,
        increase: bool,
    ) -> anyhow::Result<Option<AppAction>> {
        let key = self.entries[self.selected].key;
        // Every Float-kind TUI setting must have a TUI_FLOAT_RANGES entry;
        // `every_float_tui_setting_has_range` in `cortex::settings::tests`
        // enforces this at compile time. A missing entry at runtime means a
        // developer added a Float setting and skipped the table — surface it
        // loudly rather than silently clamping with a default.
        let Some((min, max, step)) = tui_float_range(key) else {
            tracing::warn!("Float setting '{key}' has no TUI_FLOAT_RANGES entry; ignoring step");
            return Ok(None);
        };

        let current = self.current_value(config, key);
        let val: f64 = current.parse().unwrap_or(0.0);

        let new_val = if increase {
            (val + step).min(max)
        } else {
            (val - step).max(min)
        };

        // Round to avoid floating point drift
        let decimals = if step < 0.1 { 2 } else { 1 };
        let formatted = format!("{new_val:.decimals$}");

        // For Option<f32> settings, treat decreasing to zero as "clear to None"
        // so the popup can return to the (none) display rather than getting
        // stuck at "0.00". The custom apply_setting arm interprets an empty
        // string as None.
        let payload = if key == "skills.budget_pct" && new_val == 0.0 {
            ""
        } else {
            formatted.as_str()
        };
        Ok(self.apply_and_save(config, key, payload))
    }

    fn toggle_bool(&mut self, config: &mut Config) -> anyhow::Result<Option<AppAction>> {
        let entry = &self.entries[self.selected];
        let key = entry.key;
        let current = self.current_value(config, key);
        let new_val = if current == "true" { "false" } else { "true" };
        Ok(self.apply_and_save(config, key, new_val))
    }

    /// Persist a setting via the daemon. Returns an error only when a
    /// wired daemon rejects the write; if no client is wired (unit tests
    /// that exercise the apply-to-Config path without a running daemon)
    /// the call is a best-effort no-op so the test surfaces the pure
    /// logic path. Production callers always wire a client in `show()`.
    fn save_setting(&self, key: &str, value: &str) -> anyhow::Result<()> {
        let key = key.to_string();
        let value = value.to_string();
        match self.block_on_rpc(move |c| Box::pin(async move { c.set_setting(&key, &value).await }))
        {
            Some(Ok(())) => Ok(()),
            Some(Err(e)) => Err(e),
            // No client wired or no tokio runtime current.
            None => Ok(()),
        }
    }

    /// Save a Secret setting (currently only `llm.api_key`) via the keychain
    /// helper. On success the config's `llm.api_key` is updated so the new key
    /// takes effect without a restart. On `KeychainUnavailable` the user sees
    /// an env-var fallback hint.
    fn save_secret(&mut self, config: &mut Config, key: &str, value: &str) -> Option<AppAction> {
        if key != "llm.api_key" {
            self.status_message = Some((format!("Secret save not wired for {key}"), false));
            return None;
        }

        let provider_id = config
            .llm
            .provider
            .clone()
            .unwrap_or_else(|| "openrouter".to_string());

        // `save_api_key`'s first param is a vestigial generic placeholder
        // (see api_key_store.rs) — pass the popup itself just to satisfy it.
        match api_key_store::save_api_key(&(), config, &provider_id, value) {
            Ok(ApiKeySaveOutcome::StoredInKeychain) => {
                self.status_message =
                    Some((format!("API key saved to keychain for {provider_id}"), true));
                Some(AppAction::ConfigReloaded)
            }
            Ok(ApiKeySaveOutcome::KeychainUnavailable) => {
                self.status_message = Some((api_key_store::env_var_hint(&provider_id), false));
                None
            }
            Ok(ApiKeySaveOutcome::EmptyInput) => {
                self.status_message = Some(("Enter a non-empty key".to_string(), false));
                None
            }
            Err(e) => {
                self.status_message = Some((format!("Save failed: {e}"), false));
                None
            }
        }
    }

    /// Apply a setting to config, persist to DB, and update `status_message` in one go.
    /// Returns `Some(AppAction::UpdateSetting)` on success, `None` on error.
    fn apply_and_save(&mut self, config: &mut Config, key: &str, value: &str) -> Option<AppAction> {
        match config.apply_setting(key, value) {
            Ok(confirmation) => match self.save_setting(key, value) {
                Ok(()) => {
                    self.customized_keys.insert(key.to_string());
                    self.status_message = Some((format!("Updated: {confirmation}"), true));
                    Some(AppAction::UpdateSetting {
                        key: key.to_string(),
                        value: value.to_string(),
                    })
                }
                Err(e) => {
                    self.status_message = Some((format!("Save failed: {e}"), false));
                    None
                }
            },
            Err(e) => {
                self.status_message = Some((format!("Error: {e}"), false));
                None
            }
        }
    }

    /// Reset all settings to compiled defaults by clearing DB overrides and reloading config.
    fn reset_all_to_defaults(&mut self, config: &mut Config) -> anyhow::Result<Option<AppAction>> {
        let mut failed = 0usize;
        for entry in &self.entries {
            let key = entry.key.to_string();
            let res =
                self.block_on_rpc(move |c| Box::pin(async move { c.unset_setting(&key).await }));
            match res {
                Some(Ok(())) => {}
                Some(Err(e)) => {
                    tracing::warn!("Failed to reset setting '{}': {e}", entry.key);
                    failed += 1;
                }
                // `None` = no client wired or no runtime — best-effort
                // no-op (matches `save_setting`'s no-client semantics).
                None => {}
            }
        }
        // Reload config from defaults+DB. Falls back to compiled defaults if
        // the daemon's settings table is unreadable.
        *config = crate::async_bridge::block_on(Config::load_from_db()).unwrap_or_default();
        self.refresh_customized_keys();
        self.sync_select_indices(config);
        if failed > 0 {
            self.status_message = Some((
                format!("Reset done, but {failed} setting(s) failed to clear from DB"),
                false,
            ));
        } else {
            self.status_message = Some(("All settings reset to defaults".to_string(), true));
        }
        Ok(Some(AppAction::ConfigReloaded))
    }

    /// Get the source of a setting value. Backed by the snapshot pulled in
    /// `refresh_customized_keys` so render() doesn't issue an RPC per row.
    fn setting_source(&self, key: &str) -> SettingSource {
        if self.customized_keys.contains(key) {
            SettingSource::Database
        } else {
            SettingSource::Default
        }
    }

    pub fn render(&self, frame: &mut Frame, config: &Config) {
        if !self.visible {
            return;
        }

        let area = frame.area();
        let popup_area = popup_utils::popup_area(area);

        // Model selection list mode — render dedicated list
        if let EditMode::SelectingModel {
            selected,
            scroll_offset,
        } = &self.mode
        {
            let inner = popup_utils::render_popup_frame(frame, popup_area, "Select Model");
            if inner.height < 5 || inner.width < 12 {
                return;
            }

            let provider_id = PROVIDERS
                .get(self.provider_index)
                .map(|(id, _, _)| *id)
                .unwrap_or("openrouter");
            let models = models_for_provider(provider_id);
            let content_height = (inner.height as usize).saturating_sub(2); // reserve footer + status

            let mut lines: Vec<Line<'static>> = Vec::new();
            for (i, (_, display)) in models.iter().enumerate() {
                let is_current = i == self.model_index;
                let is_sel = i == *selected;
                let bullet = if is_current { theme::BULLET } else { "○" };
                let label = format!("  {bullet} {display}");

                let style = if is_sel {
                    theme::popup_selected()
                } else {
                    ratatui::style::Style::default()
                };

                let pad = (inner.width as usize).saturating_sub(label.len() + 1);
                lines.push(Line::from(vec![
                    Span::styled(label, style),
                    Span::styled(format!("{:>pad$} ", "", pad = pad), style),
                ]));
            }

            // Scroll to keep selected visible
            let adj_scroll = if *selected >= *scroll_offset + content_height {
                *selected - content_height + 1
            } else if *selected < *scroll_offset {
                *selected
            } else {
                *scroll_offset
            };

            let visible_lines: Vec<Line<'static>> = lines
                .into_iter()
                .skip(adj_scroll)
                .take(content_height)
                .collect();

            let content_area = Rect::new(inner.x, inner.y, inner.width, content_height as u16);
            frame.render_widget(Paragraph::new(visible_lines), content_area);

            popup_utils::render_footer(
                frame,
                inner,
                " \u{2191}\u{2193}: navigate  Enter: select  Esc: cancel",
            );
            return;
        }

        let inner = popup_utils::render_popup_frame(frame, popup_area, "Settings");

        if inner.height < 5 || inner.width < 12 {
            return;
        }

        let content_height = (inner.height as usize).saturating_sub(3); // reserve footer + hint + status
        let mut lines: Vec<Line<'static>> = Vec::new();

        let mut last_category: Option<&str> = None;
        let mut row_indices: Vec<usize> = Vec::new(); // maps entry index to line index

        for (i, entry) in self.entries.iter().enumerate() {
            if last_category != Some(entry.category) {
                if last_category.is_some() {
                    lines.push(Line::default());
                }
                lines.push(Line::from(Span::styled(
                    format!(" {}", entry.category),
                    theme::bold(),
                )));
                last_category = Some(entry.category);
            }

            row_indices.push(lines.len());
            let value = self.current_value(config, entry.key);
            let source = self.setting_source(entry.key);
            let is_customized = !matches!(source, SettingSource::Default);
            let is_selected = i == self.selected;

            let display_value = if is_selected {
                if let EditMode::Editing { ref buffer } = self.mode {
                    if entry.kind == SettingKind::Secret {
                        let masked: String = buffer.chars().map(|_| '\u{2022}').collect();
                        format!("{masked}_")
                    } else {
                        format!("{buffer}_")
                    }
                } else if entry.kind == SettingKind::Bool {
                    let icon = if value == "true" {
                        theme::CHECK
                    } else {
                        theme::CROSS
                    };
                    icon.to_string()
                } else if entry.key == "model" {
                    format!("{value} \u{25B6}")
                } else if entry.kind == SettingKind::Select {
                    format!("< {value} >")
                } else {
                    value.clone()
                }
            } else if entry.kind == SettingKind::Bool {
                let icon = if value == "true" {
                    theme::CHECK
                } else {
                    theme::CROSS
                };
                icon.to_string()
            } else {
                value.clone()
            };

            let customized_suffix = if is_customized { " \u{25CF}" } else { "" };
            let label_width = inner.width.saturating_sub(4) as usize;
            let label = format!("  {}", entry.label);
            let val_with_suffix = format!("{display_value}{customized_suffix}");
            let val_len = val_with_suffix.len();
            let padding = label_width.saturating_sub(label.len() + val_len);

            let base_style = if is_selected {
                theme::popup_selected()
            } else {
                ratatui::style::Style::default()
            };

            let mut spans = vec![
                Span::styled(label.clone(), base_style),
                Span::styled(format!("{:>pad$}", "", pad = padding), base_style),
                Span::styled(display_value, base_style),
            ];
            if is_customized {
                spans.push(Span::styled(" \u{25CF}", base_style.patch(theme::dim())));
            }
            // Fill remaining space with base style for consistent highlight
            spans.push(Span::styled(" ", base_style));

            lines.push(Line::from(spans));
        }

        // Scroll to keep selected visible
        let selected_line = row_indices.get(self.selected).copied().unwrap_or(0);
        let scroll_offset = if selected_line >= content_height {
            selected_line - content_height + 1
        } else {
            0
        };

        let visible_lines: Vec<Line<'static>> = lines
            .into_iter()
            .skip(scroll_offset)
            .take(content_height)
            .collect();

        let content_area = Rect::new(inner.x, inner.y, inner.width, content_height as u16);
        frame.render_widget(Paragraph::new(visible_lines), content_area);

        popup_utils::render_status_message(frame, inner, self.status_message.as_ref(), 3);

        // CLI hint
        let cli_hint_y = inner.y + inner.height - 2;
        let cli_hint_area = Rect::new(inner.x, cli_hint_y, inner.width, 1);
        frame.render_widget(
            Paragraph::new(Line::from(Span::styled(
                " More: borg settings set <key> <value>".to_string(),
                theme::dim(),
            ))),
            cli_hint_area,
        );

        // Footer hint (context-sensitive)
        let hint = match self.mode {
            EditMode::Browsing => {
                let entry = &self.entries[self.selected];
                if entry.key == "model" {
                    " Enter: choose model  r: reset  Esc: close"
                } else {
                    match entry.kind {
                        SettingKind::Bool => " Space: toggle  Enter: apply  r: reset  Esc: close",
                        SettingKind::Select => {
                            " \u{25C0}\u{25B6}: cycle  Enter: apply  r: reset  Esc: close"
                        }
                        SettingKind::Float => {
                            " \u{25C0}\u{25B6}: adjust  Enter: edit  r: reset  Esc: close"
                        }
                        _ => " Enter: edit  r: reset  Esc: close",
                    }
                }
            }
            EditMode::ConfirmReset => {
                " Reset all settings to defaults? y: confirm  any key: cancel"
            }
            EditMode::Editing { .. } => " Enter: apply  Esc: cancel",
            EditMode::SelectingModel { .. } => {
                " \u{2191}\u{2193}: navigate  Enter: select  Esc: cancel"
            }
        };
        popup_utils::render_footer(frame, inner, hint);
    }
}

impl PopupHandler for SettingsPopup {
    fn is_visible(&self) -> bool {
        self.visible
    }

    fn handle_key_event(
        &mut self,
        key: crossterm::event::KeyEvent,
        config: &mut Config,
    ) -> anyhow::Result<Option<AppAction>> {
        self.handle_key(key, config)
    }

    fn handle_paste_event(&mut self, text: &str) -> bool {
        self.handle_paste(text)
    }

    fn wants_text_input(&self) -> bool {
        matches!(self.mode, EditMode::Editing { .. })
    }
}

