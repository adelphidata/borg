//! Settings resolution layer: DB → compiled defaults.

use anyhow::{Context, Result};

use crate::config::Config;
use crate::db::Database;

/// Where a setting's effective value came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SettingSource {
    Default,
    Database,
}

impl std::fmt::Display for SettingSource {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            SettingSource::Default => write!(f, "default"),
            SettingSource::Database => write!(f, "db"),
        }
    }
}

/// One entry in the full settings listing.
#[derive(Debug, Clone)]
pub struct SettingInfo {
    pub key: String,
    pub value: String,
    pub source: SettingSource,
}

pub type SettingExtractor = fn(&Config) -> String;

// SETTING_REGISTRY is generated by the define_settings! macro in config/settings_table.rs
pub use crate::config::settings_table::{
    SETTING_REGISTRY, TUI_FLOAT_RANGES, TUI_SELECT_CHOICES, TUI_SETTINGS,
};

/// Return the static choice list for a `Select`-kind TUI setting, if one is
/// declared in `TUI_SELECT_CHOICES`. `provider` and `model` are dynamic and
/// return `None`.
pub fn tui_select_choices(key: &str) -> Option<&'static [&'static str]> {
    TUI_SELECT_CHOICES
        .iter()
        .find(|(k, _)| *k == key)
        .map(|(_, v)| *v)
}

/// Return the `(min, max, step)` tuple for a `Float`-kind TUI setting, if one
/// is declared in `TUI_FLOAT_RANGES`.
pub fn tui_float_range(key: &str) -> Option<(f64, f64, f64)> {
    TUI_FLOAT_RANGES
        .iter()
        .find(|(k, _, _, _)| *k == key)
        .map(|(_, min, max, step)| (*min, *max, *step))
}

/// How a TUI settings popup should render and edit a setting.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TuiSettingKind {
    /// Boolean toggle (Space toggles).
    Bool,
    /// Float with arrow-step (±0.1).
    Float,
    /// Unsigned integer (Enter opens edit buffer).
    Uint,
    /// Select from an enum/provider list (Left/Right cycles).
    Select,
    /// Free-form string (Enter opens plain-text edit buffer).
    Text,
    /// Secret value (Enter opens masked edit buffer; list row shows `(set)`/`(not set)`,
    /// never the raw value). Persisted via keychain-backed save path.
    Secret,
}

/// Display metadata for a TUI-visible setting. Emitted by the `tui_settings`
/// block of `define_settings!` so the popup list lives alongside the registry
/// rather than in a separate source of truth.
#[derive(Debug, Clone, Copy)]
pub struct TuiSettingDecl {
    /// Key in `SETTING_REGISTRY`. Must resolve at runtime.
    pub key: &'static str,
    /// Human-facing label shown in the popup row.
    pub label: &'static str,
    /// Control type for input handling.
    pub kind: TuiSettingKind,
    /// Section header under which this entry renders.
    pub category: &'static str,
}

/// All known setting keys, derived from `SETTING_REGISTRY`.
pub static ALL_SETTING_KEYS: std::sync::LazyLock<Vec<&'static str>> =
    std::sync::LazyLock::new(|| SETTING_REGISTRY.iter().map(|(k, _)| *k).collect());

/// Process-wide dedup set for invalid-setting warnings. The config watcher
/// reloads every ~3 s, and each reload iterates every row in the `settings`
/// table — without dedup, stale or unknown keys produced thousands of
/// identical warn lines per hour (~20 MB / day of log noise). We warn once
/// per unique `(key, error-message)` pair per process lifetime.
static WARNED_INVALID_SETTINGS: std::sync::OnceLock<
    std::sync::Mutex<std::collections::HashSet<String>>,
> = std::sync::OnceLock::new();

/// Emit a `warn!` for an invalid setting, at most once per unique
/// `(key, error)` pair over the lifetime of the process.
pub fn warn_invalid_setting_once(key: &str, err: &anyhow::Error) {
    let msg = format!("{err}");
    let fingerprint = format!("{key}\0{msg}");
    let set = WARNED_INVALID_SETTINGS.get_or_init(Default::default);
    let mut guard = match set.lock() {
        Ok(g) => g,
        Err(poisoned) => poisoned.into_inner(),
    };
    if guard.insert(fingerprint) {
        tracing::warn!("Ignoring invalid setting {key}: {msg}");
    }
}

/// True for keys whose change has security posture implications and should
/// land in the hash-chained audit log.
///
/// Why: `audit_log_chain` brackets every security-relevant state change.
/// Emitting on *every* settings write would bloat the chain with LLM-tuning
/// noise (`temperature`, `theme`, …), so this allow-list scopes the firing
/// to keys whose change would shift posture, sandbox boundaries, or
/// retention behavior.
pub fn is_security_relevant_setting(key: &str) -> bool {
    const PREFIXES: &[&str] = &["security.", "sandbox.", "data."];
    PREFIXES.iter().any(|p| key.starts_with(p))
}

/// Append a `SETTINGS_CHANGED` audit event when `key` is security-relevant
/// and the value actually changed. Old/new values are truncated to keep
/// the chain bounded — full values are still in the `settings` table.
async fn emit_settings_changed_if_relevant(key: &str, old: Option<&str>, new: Option<&str>) {
    if !is_security_relevant_setting(key) {
        return;
    }
    if old == new {
        return;
    }
    crate::db::try_emit_global(
        crate::db::audit_events::SETTINGS_CHANGED,
        "system",
        &serde_json::json!({
            "key": key,
            "old": old.map(truncate_setting_value_for_audit),
            "new": new.map(truncate_setting_value_for_audit),
        }),
    )
    .await;
}

fn truncate_setting_value_for_audit(v: &str) -> String {
    const MAX: usize = 256;
    if v.len() <= MAX {
        v.to_string()
    } else {
        let mut s: String = v.chars().take(MAX).collect();
        s.push_str("…<truncated>");
        s
    }
}

/// Merges settings from two layers: DB overrides → compiled defaults.
pub struct SettingsResolver {
    db: Database,
}

impl SettingsResolver {
    /// Open the database for settings resolution.
    pub async fn load() -> Result<Self> {
        let db = Database::open()
            .await
            .with_context(|| "Failed to open database for settings")?;
        Ok(Self { db })
    }

    /// Build from a pre-existing Database.
    pub fn new(db: Database) -> Self {
        Self { db }
    }

    /// Resolve a full Config from defaults + DB overrides.
    pub async fn resolve(&self) -> Result<Config> {
        let mut config = Config::default();
        let db_settings = self.db.list_settings().await?;
        for (key, value, _) in &db_settings {
            if let Err(e) = config.apply_setting(key, value) {
                warn_invalid_setting_once(key, &e);
            }
        }
        Ok(config)
    }

    /// Validate and write a setting to the database.
    /// Returns the confirmation string from `apply_setting`.
    pub async fn set(&self, key: &str, value: &str) -> Result<String> {
        // Validate by applying to a throwaway config
        let mut scratch = Config::default();
        let confirmation = scratch.apply_setting(key, value)?;
        let prev = self.read_prior_for_audit(key).await;
        self.db.set_setting(key, value).await?;
        emit_settings_changed_if_relevant(key, prev.as_deref(), Some(value)).await;
        // Clearing a parent blob (`llm.aux = ""`) must also wipe its
        // sub-key rows. Settings replay applies all rows in lex order, so
        // a leftover `llm.aux.model = "<old>"` would auto-resurrect aux
        // on the next reload — silently negating the user's clear.
        if key == "llm.aux" && value.trim().is_empty() {
            self.cascade_clear_aux_subkeys().await;
        }
        Ok(confirmation)
    }

    /// Revert a setting to its compiled default value.
    /// Writes the default back to the DB rather than deleting the row,
    /// keeping the settings table as the complete source of truth.
    pub async fn unset(&self, key: &str) -> Result<()> {
        let defaults = Config::default();
        let default_value = config_value_for_key(&defaults, key)
            .ok_or_else(|| anyhow::anyhow!("Unknown setting key: {key}"))?;
        let prev = self.read_prior_for_audit(key).await;
        self.db.set_setting(key, &default_value).await?;
        emit_settings_changed_if_relevant(key, prev.as_deref(), Some(&default_value)).await;
        // `unset llm.aux` writes the default ("") for the parent and must
        // cascade — see the matching path in `set` for rationale.
        if key == "llm.aux" {
            self.cascade_clear_aux_subkeys().await;
        }
        Ok(())
    }

    /// Best-effort delete of `llm.aux.model` / `llm.aux.fallback` rows so
    /// they can't resurrect aux on the next `resolve()`. DB errors are
    /// logged, not propagated — a stale sub-key is a soft-fail (worst
    /// case: aux re-materializes with the old model id, which the user
    /// can fix by editing the row).
    async fn cascade_clear_aux_subkeys(&self) {
        for sub_key in ["llm.aux.model", "llm.aux.fallback"] {
            if let Err(e) = self.db.delete_setting(sub_key).await {
                tracing::warn!(
                    %sub_key,
                    error = %e,
                    "settings: cascade-delete of aux sub-key failed; \
                     may resurrect aux on next reload"
                );
            }
        }
    }

    /// Read the prior value of `key` for the `SETTINGS_CHANGED` audit row.
    /// A read failure is non-fatal — we still want the write to land — but
    /// CLAUDE.md's no-silent-swallowing invariant requires we log it so
    /// operators can spot when audit fidelity is degraded.
    async fn read_prior_for_audit(&self, key: &str) -> Option<String> {
        match self.db.get_setting(key).await {
            Ok(v) => v,
            Err(e) => {
                tracing::warn!(
                    %key,
                    error = %e,
                    "settings: prior-value read failed; SETTINGS_CHANGED audit row will record old=null",
                );
                None
            }
        }
    }

    /// Get the effective value and its source for a single key.
    /// Source is determined by comparing the DB value to the compiled default:
    /// matching values report `Default`, differing values report `Database`.
    pub async fn get_with_source(&self, key: &str) -> Result<(String, SettingSource)> {
        let defaults = Config::default();
        let default_value = config_value_for_key(&defaults, key)
            .ok_or_else(|| anyhow::anyhow!("Unknown setting key: {key}"))?;

        if let Some(db_value) = self.db.get_setting(key).await? {
            let source = if db_value == default_value {
                SettingSource::Default
            } else {
                SettingSource::Database
            };
            return Ok((db_value, source));
        }

        // Fallback for keys not yet seeded (e.g. new setting added between startups)
        Ok((default_value, SettingSource::Default))
    }

    /// List all settings with their effective values and sources.
    pub async fn list_all(&self) -> Result<Vec<SettingInfo>> {
        let mut result = Vec::new();
        for &key in ALL_SETTING_KEYS.iter() {
            match self.get_with_source(key).await {
                Ok((value, source)) => result.push(SettingInfo {
                    key: key.to_string(),
                    value,
                    source,
                }),
                Err(e) => {
                    tracing::warn!("Failed to resolve setting {key}: {e}");
                    continue;
                }
            }
        }
        Ok(result)
    }

    /// Access the underlying database.
    pub fn database(&self) -> &Database {
        &self.db
    }
}

/// Extract the current string value of a config key.
pub fn config_value_for_key(config: &Config, key: &str) -> Option<String> {
    SETTING_REGISTRY
        .iter()
        .find(|(k, _)| *k == key)
        .map(|(_, extract)| extract(config))
}

